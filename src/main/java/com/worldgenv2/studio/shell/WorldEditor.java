package com.worldgenv2.studio.shell;

import com.worldgenv2.studio.project.Asset;
import com.worldgenv2.studio.project.J;
import com.worldgenv2.studio.ui.*;

/** World Settings: vertical range and sea level, with a proportional preview bar. */
final class WorldEditor extends Editor {

    private record Preset(String id, String label, int minY, int depth, int sea) {}

    private static final Preset[] PRESETS = {
            new Preset("standard", "Standard (Y -64 to 320)", -64, 384, 63),
            new Preset("hytale_320", "Hytale Default 320 (Y 0 to 320)", 0, 320, 100),
            new Preset("hytale_512", "Hytale Canonical 512 (Y 0 to 512)", 0, 512, 128),
            new Preset("hytale_extended", "Hytale Extended 576 (Y -64 to 512)", -64, 576, 128),
            new Preset("epic_1024", "Epic 1024 (Y -64 to 960)", -64, 1024, 128),
            new Preset("custom", "Custom", -64, 384, 63),
    };

    WorldEditor(StudioApp app, Asset a) { super(app, a); }

    @Override
    protected void build() {
        section("Vertical Range", "applies to every dimension generated by Worldgen V2");
        Dropdown preset = choiceNoEdit();
        field("Preset", preset, "Picking a preset fills in the three values below.");
        field("Min Y", num("minY", -64, -2048, 0, 16, true, "Min Y"), "Lowest block generated. Use a multiple of 16.");
        field("World depth", num("genDepth", 384, 64, 4096, 16, true, "World depth"), "Total blocks of height. Ceiling = Min Y + depth.");
        field("Sea level", num("seaLevel", 63, -2048, 4096, 1, true, "Sea level"), "Altitude where oceans and rivers fill.");
        Label ceiling = new Label("");
        field("Ceiling Y", ceiling);
        bind(() -> ceiling.text = String.valueOf((int) (getNum("minY", -64) + getNum("genDepth", 384))));
        block(new HeightBar());
        note("Edits save with Ctrl+S. Dimensions inherit this range. A world gets this height when it is created from this setup: change it, save, "
            + "then create the world (a height you have not used before is ready the next time the Create World screen opens).", Ui.TEXT_FAINT);
    }

    private Dropdown choiceNoEdit() {
        Dropdown d = new Dropdown();
        java.util.List<String> ids = new java.util.ArrayList<>();
        for (Preset p : PRESETS) ids.add(p.id());
        d.options(ids);
        d.display = id -> { for (Preset p : PRESETS) if (p.id().equals(id)) return p.label(); return id; };
        d.onSelect = id -> {
            for (Preset p : PRESETS) {
                if (!p.id().equals(id)) continue;
                edit("World preset", j -> {
                    j.addProperty("preset", id);
                    if (!id.equals("custom")) {
                        J.setNum(j, "minY", p.minY());
                        J.setNum(j, "genDepth", p.depth());
                        J.setNum(j, "seaLevel", p.sea());
                    }
                });
            }
        };
        bind(() -> d.selected(getStr("preset", "standard")));
        return d;
    }

    /** Touching any number while a named preset is selected turns the preset into "custom". */
    @Override
    protected void edit(String label, java.util.function.Consumer<com.google.gson.JsonObject> m) {
        super.edit(label, j -> {
            m.accept(j);
            if (label.equals("World preset")) return;
            String id = J.str(j, "preset", "custom");
            for (Preset p : PRESETS) {
                if (!p.id().equals(id) || id.equals("custom")) continue;
                if (J.integer(j, "minY", p.minY()) != p.minY() || J.integer(j, "genDepth", p.depth()) != p.depth()
                        || J.integer(j, "seaLevel", p.sea()) != p.sea()) {
                    j.addProperty("preset", "custom");
                }
            }
        });
    }

    /** Stacked proportional view: below sea (water), above sea (air), with Y labels. */
    private final class HeightBar extends Widget {
        HeightBar() { h = 42; }

        @Override
        protected void render(Gfx g, int mx, int my) {
            int minY = (int) getNum("minY", -64), depth = Math.max(1, (int) getNum("genDepth", 384)), sea = (int) getNum("seaLevel", 63);
            g.box(x, y, w, 20, Ui.BG_INPUT, Ui.LINE_STRONG);
            float under = Math.max(0f, Math.min(1f, (sea - minY) / (float) depth));
            int uw = (int) ((w - 2) * under);
            g.fill(x + 1, y + 1, uw, 18, 0xFF1B3A5C);
            g.fill(x + 1 + uw, y + 1, w - 2 - uw, 18, 0xFF161B26);
            if (uw > 0 && uw < w - 2) g.fill(x + 1 + uw, y + 1, 1, 18, Ui.CYAN);
            g.textMid("Y " + minY, x + 5, y, 20, Ui.TEXT_DIM);
            g.textCentered("sea " + sea, x, y, w, 20, Ui.CYAN);
            g.textRight("Y " + (minY + depth), x + w - 5, y, 20, Ui.TEXT_DIM);
            g.text("bedrock / deepslate", x + 1, y + 25, Ui.TEXT_FAINT);
            g.text("open air", x + w - g.width("open air") - 1, y + 25, Ui.TEXT_FAINT);
        }
    }
}
