import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.block.state.BlockState;
import org.slf4j.Logger;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ExecutorService;
import java.util.function.Consumer;

/**
 * Distant Horizons integration. DH normally builds far terrain by running Minecraft's whole chunk pipeline for every distant chunk.
 * For a level generated by Worldgen V2 we register our own DH world generator instead (the way the "SeedGen" mods do for vanilla):
 * each far chunk comes straight from the engine's terrain tiles, already stored as runs of equal blocks, which is exactly the shape
 * DH wants (a column of block runs). Surface mode gives terrain only; Features mode adds the props (trees, rocks), generated the same
 * way real chunks are. Nothing here runs unless DH is installed.
 */
public final class DistantHorizonsCompat {
    private static final Logger LOGGER = LogUtils.getLogger();

    private DistantHorizonsCompat() {}

    public static void init() {
        DhApiEventRegister.on(DhApiLevelLoadEvent.class, new DhApiLevelLoadEvent() {
            @Override
            public void onLevelLoad(DhApiEventParam<EventParam> input) {
                IDhApiLevelWrapper wrapper = input.value.levelWrapper;
                if (!(wrapper.getWrappedMcObject() instanceof ServerLevel level)) return;
                if (!(level.getChunkSource().getGenerator() instanceof WorldGenV2ChunkGenerator generator)) return;
                var result = DhApi.worldGenOverrides.registerWorldGeneratorOverride(wrapper, new Generator(level, generator, wrapper));
                if (result.success) LOGGER.info("[Worldgen V2] Distant Horizons will build far terrain for {} straight from the generator", level.dimension());
                else LOGGER.warn("[Worldgen V2] Distant Horizons did not take our generator for {}: {}", level.dimension(), result.message);
            }
        });
        LOGGER.info("[Worldgen V2] Distant Horizons found: far terrain will come straight from the generator");
    }

    /** Far chunks for one level, as DH API chunks (block runs per column). */
    private static final class Generator implements IDhApiWorldGenerator {
        private final ServerLevel level;
        private final WorldGenV2ChunkGenerator generator;
        private final IDhApiLevelWrapper wrapper;
        private final Map<BlockState, IDhApiBlockStateWrapper> blocks = new ConcurrentHashMap<>();
        private final Map<Holder<Biome>, IDhApiBiomeWrapper> biomes = new ConcurrentHashMap<>();

        Generator(ServerLevel level, WorldGenV2ChunkGenerator generator, IDhApiLevelWrapper wrapper) {
            this.level = level;
            this.generator = generator;
            this.wrapper = wrapper;
        }

        @Override
        public EDhApiWorldGeneratorReturnType getReturnType() { return EDhApiWorldGeneratorReturnType.API_CHUNKS; }

        @Override
        public CompletableFuture<Void> generateApiChunks(int chunkPosMinX, int chunkPosMinZ, int width, byte targetDataDetail,
                                                         EDhApiDistantGeneratorMode mode, ExecutorService pool, Consumer<DhApiChunk> resultConsumer) {
            return CompletableFuture.runAsync(() -> {
                for (int cx = chunkPosMinX; cx < chunkPosMinX + width; cx++)
                    for (int cz = chunkPosMinZ; cz < chunkPosMinZ + width; cz++)
                        resultConsumer.accept(timed(cx, cz, mode));
            }, pool);
        }

        private static final java.util.concurrent.atomic.AtomicLong COUNT = new java.util.concurrent.atomic.AtomicLong(), NANOS = new java.util.concurrent.atomic.AtomicLong();

        /** One far chunk, with a running count and average cost in the log every 2000 chunks. */
        private DhApiChunk timed(int cx, int cz, EDhApiDistantGeneratorMode mode) {
            long t0 = System.nanoTime();
            DhApiChunk c = chunk(cx, cz, mode);
            long n = COUNT.incrementAndGet(), ns = NANOS.addAndGet(System.nanoTime() - t0);
            if (n == 1 || n % 2000 == 0) LOGGER.info("[Worldgen V2] Distant Horizons: {} far chunks built ({} mode), {} ms each on average", n, mode, String.format("%.1f", ns / 1e6 / n));
            return c;
        }

        private DhApiChunk chunk(int cx, int cz, EDhApiDistantGeneratorMode mode) {
            int minY = level.getMinY(), maxY = level.getMaxY();
            StagedChunkGenerator<BlockState> engine = generator.getStagedGenerator();
            boolean withProps = mode != EDhApiDistantGeneratorMode.SURFACE;
            ImmutableChunkSnapshot<BlockState> snap = engine.lodSnapshot(cx, cz, minY, maxY, withProps);
            DhApiChunk out = DhApiChunk.create(cx, cz, minY, maxY);
            byte detail = EDhApiDetailLevel.BLOCK.detailLevel;
            var biomeSource = generator.getBiomeSource();
            var sampler = level.getChunkSource().randomState().sampler();
            List<DhApiTerrainDataPoint> column = new ArrayList<>();
            for (int lx = 0; lx < 16; lx++) {
                for (int lz = 0; lz < 16; lz++) {
                    column.clear();
                    int runs = snap.runCount(lx, lz);
                    // the biome at the surface of the column (the topmost block that is not air)
                    int surface = 0;
                    for (int i = runs - 1; i >= 0; i--) {
                        if (!snap.runBlock(lx, lz, i).isAir()) { surface = snap.runEnd(lx, lz, i) - 1; break; }
                    }
                    int wx = (cx << 4) + lx, wz = (cz << 4) + lz;
                    Holder<Biome> holder = biomeSource.getNoiseBiome(wx >> 2, (minY + surface) >> 2, wz >> 2, sampler);
                    IDhApiBiomeWrapper biome = biomes.computeIfAbsent(holder, h -> DhApi.Delayed.wrapperFactory.getBiomeWrapper(new Object[]{h}, wrapper));
                    // top down: open sky lights air and fluids until the first solid run
                    boolean sky = true;
                    for (int i = runs - 1; i >= 0; i--) {
                        BlockState state = snap.runBlock(lx, lz, i);
                        int top = snap.runEnd(lx, lz, i), bottom = i == 0 ? 0 : snap.runEnd(lx, lz, i - 1);
                        boolean clear = state.isAir() || !state.getFluidState().isEmpty();
                        int skyLight = clear && sky ? 15 : 0;
                        if (!clear) sky = false;
                        int blockLight = state.getLightEmission();
                        IDhApiBlockStateWrapper block = blocks.computeIfAbsent(state, s -> DhApi.Delayed.wrapperFactory.getBlockStateWrapper(new Object[]{s}, wrapper));
                        column.add(DhApiTerrainDataPoint.create(detail, blockLight, skyLight, bottom, top, block, biome));
                    }
                    out.setDataPoints(lx, lz, column);
                }
            }
            return out;
        }

        @Override
        public void preGeneratorTaskStart() { }

        @Override
        public void close() { }
    }
}
